-- Profil dibuat otomatis saat akun auth baru terdaftar — dari metadata signUp.
-- Menutup celah "akun yatim" (ada di auth.users tapi tidak punya baris profiles)
-- yang terjadi bila insert profil dari klien gagal/terputus.

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1)),
    coalesce(new.raw_user_meta_data->>'role', 'siswa')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();
